// Package secret is the box's secret inventory and the rotation path for the
// class that can be rotated.
//
// # What it is for
//
// Every box holds the same set of secrets, because the kit substrate installer
// creates the same ones in the same namespaces. What is NOT the same is which
// of them can be rotated: muse's vault key seals every stored credential, so a
// rotation forks all of them, and identity's OIDC signing key is the only key
// its JWKS publishes, so a rotation is a cutover with no overlap window. An
// operator who does not know the difference spends a weekend discovering it.
//
// This package is that difference, written down. It enumerates what the box
// holds, classes each entry rotatable / conditional / not-rotatable, and
// records the REASON with the file and line that says so — so the answer to
// "why can't I rotate this" is a citation rather than an opinion.
//
// # Where the enumeration comes from
//
// The kit installer's SECRET RECORD block is the source of truth for what
// exists: every name it lists is created by install_service_secrets below it,
// and kit's own substrate test parses the block and fails if a fixture removes
// one. This package is the same claim on the Go side, for the fleet side of
// the same substrate. Three entries the record does not carry are here because
// the runbooks that name them are the reason this packet exists: the Redis
// password and the Postgres role passwords (both generated by the installer but
// not listed in the record's four namespaces) and muse's MUSE_VAULT_KEY.
//
// The citations in this package point at the FLEET's sources, which are not
// paths in this repository: the kit installer, identity's runbook, muse's
// runbook and the packet record. That is deliberate and it is the cost of the
// split — caf cannot vendor a copy of kit's install script and stay honest,
// because a copy that drifted would be a second source of truth that disagreed
// with the first. The citations are checkable by hand against the fleet, and
// they are the reason each class claim is a sentence with an address rather
// than a bare word.
//
// # The one invariant
//
// THE INVENTORY NEVER READS A SECRET'S VALUE. It names the Kubernetes Secret
// object and the key inside it, and the read it performs — the plan's presence
// check — is spelled so that only key NAMES ever reach this process: the
// go-template ranges over .data and prints $k, never $v. Nothing in this
// package can print, log or base64-decode a value, because no field holds one
// and no step captures one. That is the same property internal/box has about a
// private key, and it is the reason a rotation can be reported without the
// report being dangerous to paste into a ticket.
//
// # The three classes, and what each one buys
//
//	rotatable     replace the key in place and restart the deployment. The
//	              installer already records the posture: "rotate by replacing
//	              the secret and restarting the pods".
//	conditional   the rotation is possible but not by a kubectl patch alone:
//	              a second write, a re-mint against identity's API, an
//	              ALTER ROLE in Postgres, or a provider-side change. The
//	              reason names which. A command that rotated one of these by
//	              itself would produce the outage it was run to prevent.
//	not-rotatable the rotation is a fork or a cutover. The reason names
//	              which, and the command REFUSES with it rather than
//	              skipping silently — a silent skip is how somebody spends
//	              the weekend.
//
// # The schedule
//
// "On a schedule" is a state file, not a timer. This package computes which
// entries are DUE from the last-rotated timestamp it records after each
// rotation, so the schedule is a fact about the last run rather than a cron
// line nobody can see. The file holds no secret and no credential: names,
// timestamps and the reason a rotation was refused.
//
// # The seams
//
// Runner is every kubectl invocation, and it is an interface so a test can
// record what a rotation would run without a cluster anywhere in sight — the
// same seam internal/backup and internal/deploy use, for the same reason.
