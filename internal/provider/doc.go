// Package provider is the client half of the sealed-connection model
// (anywaye/notes/agents-first.md, boundary 6 and the W3 table row "the agent hands over
// an envelope; it never sees the value").
//
// A provider credential is sealed to the BOX's public key and the resulting
// envelope is what is handed to box. Box persists the envelope and
// cannot open it — it holds no box private key — and the box, holding the
// private half, is the only thing that can. The agent that runs
// ` + "`cafe provider connect`" + ` is a courier of the envelope and never a holder
// of the value: the credential is sealed in memory at the moment it is read
// and is never printed, logged or stored anywhere but inside the envelope.
//
// WHY X25519 AND NOT BOX'S RSA. Box's own SealedEnvelope
// (app/models/sealed_envelope.rb) seals with RSA-OAEP to a PEM RSA public key
// of at least 2048 bits. The box's keypair, generated by `cafe box enroll`
// (internal/box), is ed25519 — a signature key, 32 bytes, with no RSA
// equivalent. An envelope sealed to an RSA key the box does not hold would be
// an envelope nobody can open, which is worse than none: boundary 6's whole
// content is that the box CAN open what box stores.
//
// The standard answer, and the one this package uses, is the ed25519→X25519
// conversion: the same keypair, viewed as a Montgomery (Diffie-Hellman) key
// rather than an Edwards (signature) key. The public half converts by the
// birational map u = (1+y)/(1-y); the private half by SHA-512 of the seed with
// the X25519 clamp. This is the construction NaCl's crypto_box and Signal's
// XEdDSA are built on, and it is why the box's ONE keypair can both sign (its
// identity, W2-P6) and receive sealed credentials (this package) without a
// second key.
//
// The envelope is JSON — {v, alg, key, iv, tag, data}, every field but v/alg
// base64 — the same shape box's SealedEnvelope produces, so the column
// the model already has stores either. The one difference is the algorithm
// name: this package writes "X25519+A256GCM" and `key` carries the
// ephemeral X25519 public key rather than a wrapped one, because ECDH derives
// the shared secret directly and there is nothing to wrap. Box never
// opens an envelope, so the difference is invisible to it; the box opens both
// with the same code.
//
// THE ROUTE IS NOT IN BOX YET, and that is a fact about box, not
// about this package. W3-P2 merged the model, the migration and the sealing
// primitive but no HTTP route; `cafe provider connect` POSTs to
// /v1/email-provider-connections and `cafe provider status` GETs the same
// resource, which is the RESTful shape the model's own name implies and the one
// a box endpoint will land on. The client is built against the documented
// shape — the model's fields and the envelope format — and says so in its
// report rather than pretending the route exists.
//
// Stdlib only, like internal/box: the reclamation path and the sealing path
// are the two that must keep working when nothing else does, and a dependency
// graph on the path that seals a credential is a graph that can fail to load at
// exactly the wrong moment.
